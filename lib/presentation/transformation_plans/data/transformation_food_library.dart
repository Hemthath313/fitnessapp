  /// Returns safe substitute options for a given food item, filtering out
  /// user allergens and respecting dietary preference.
  static List<TransformationFoodItem> getSafeSubstitutes({
    required String foodId,
    required List<String> userAllergies,
    required String? dietaryPreference,
  }) {
    final original = getById(foodId);
    if (original == null) return [];

    final normalizedPref = (dietaryPreference ?? 'non-vegetarian').trim().toLowerCase();
    final isVeg = normalizedPref.contains('veg') && !normalizedPref.contains('non');
    final isVegan = normalizedPref.contains('vegan');

    final cleanAllergies = userAllergies.map((a) => a.trim().toLowerCase()).toList();

    final substitutes = <TransformationFoodItem>[];

    for (final subId in original.substituteFoodIds) {
      final sub = getById(subId);
      if (sub == null) continue;

      // Check dietary preference
      if (isVegan && sub.dietaryCategory != 'vegan') continue;
      if (isVeg && sub.dietaryCategory == 'non_vegetarian') continue;

      // Check allergen safety
      final containsAllergen = sub.allergens.any((subAllergen) =>
          cleanAllergies.any((userAllergen) =>
              subAllergen.contains(userAllergen) || userAllergen.contains(subAllergen)));
      if (containsAllergen) continue;

      substitutes.add(sub);
    }

    return substitutes;
  }
